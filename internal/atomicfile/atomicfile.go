// Package atomicfile — запись файлов состояния, переживающая внезапное
// отключение питания.
//
// Одного «записать во временный файл и переименовать» мало: на XFS и ext4
// с отложенным выделением блоков данные попадают на диск позже, чем
// переименование. Если питание пропадёт между ними, после загрузки на месте
// файла окажется пустой (0 байт) файл — так однажды пропал config.json,
// и вся сеть осталась без интернета. Поэтому данные сбрасываются на диск
// (fsync) до переименования, а после него — сам каталог, чтобы новое имя
// тоже пережило сбой.
package atomicfile

import (
	"os"
	"path/filepath"
	"runtime"
)

// Write атомарно заменяет содержимое path на data: после сбоя в любой момент
// на месте файла остаётся либо прежнее содержимое, либо новое целиком.
// Временный файл — path+".tmp" в том же каталоге (переименование атомарно
// только в пределах одной файловой системы).
func Write(path string, data []byte, perm os.FileMode) error {
	tmp := path + ".tmp"
	// Остаток прошлой оборванной попытки удаляем: O_TRUNC сохранил бы его права,
	// а perm применяется только при создании файла.
	_ = os.Remove(tmp)
	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, perm)
	if err != nil {
		return err
	}
	_, err = f.Write(data)
	if err == nil {
		err = f.Sync()
	}
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = os.Remove(tmp)
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	SyncDir(filepath.Dir(path))
	return nil
}

// SyncDir сбрасывает на диск запись каталога (новые имена, переименования).
// Ошибку не возвращает: данные файла к этому моменту уже на диске, и худшее,
// что грозит при сбое, — останется прежняя версия файла, а не пустой файл.
// Отказ же здесь сообщил бы «не сохранено» о файле, который уже заменён.
// В Windows каталог так открыть нельзя, а NTFS журналирует переименование сама.
func SyncDir(dir string) {
	if runtime.GOOS == "windows" {
		return
	}
	d, err := os.Open(dir)
	if err != nil {
		return
	}
	_ = d.Sync()
	_ = d.Close()
}
